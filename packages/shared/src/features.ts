export const GARAGE_LIMITS = { fuel: 500, services: 40, docs: 30 } as const;

export function sanitizeVehicleProfile(raw: unknown, current: VehicleProfile): VehicleProfile {
  const next = { ...current };
  if (!isObj(raw)) return next;
  const name = str(raw.name, 40);
  if (name !== null) next.name = name;
  const plate = str(raw.plate, 16);
  if (plate !== null) next.plate = plate.toUpperCase();
  if (raw.fuelType === null) next.fuelType = null;
  else {
    const ft = oneOf(FUEL_TYPES, raw.fuelType);
    if (ft) next.fuelType = ft;
  }
  if (raw.tankL === null) next.tankL = null;
  else {
    const t = inRange(raw.tankL, 5, 400);
    if (t !== null) next.tankL = Math.round(t * 10) / 10;
  }
  if (raw.odometerKm === null) {
    next.odometerKm = null;
    next.odometerAt = null;
  } else {
    const o = inRange(raw.odometerKm, 0, 5_000_000);
    if (o !== null) {
      next.odometerKm = Math.round(o * 10) / 10;
      next.odometerAt = Date.now();
    }
  }
  return next;
}

export function sanitizeFuelEntry(raw: unknown): Omit<FuelEntry, 'id'> | null {
  if (!isObj(raw)) return null;
  if (!isIsoDate(raw.date)) return null;
  const odometerKm = inRange(raw.odometerKm, 0, 5_000_000);
  const liters = inRange(raw.liters, 0.1, 1000);
  if (odometerKm === null || liters === null) return null;
  const blank = raw.cost === null || raw.cost === undefined || raw.cost === '';
  const cost = blank ? null : inRange(raw.cost, 0, 100_000);
  if (!blank && cost === null) return null;
  return {
    date: raw.date,
    odometerKm: Math.round(odometerKm * 10) / 10,
    liters: Math.round(liters * 100) / 100,
    cost: cost === null ? null : Math.round(cost * 100) / 100,
    full: raw.full !== false,
    note: str(raw.note, 80) ?? '',
  };
}

export function sanitizeServiceItem(raw: unknown): Omit<ServiceItem, 'id'> | null {
  if (!isObj(raw)) return null;
  const name = str(raw.name, 40);
  if (!name) return null;
  const blank = (v: unknown) => v === null || v === undefined || v === '';
  const everyKm = blank(raw.everyKm) ? null : inRange(raw.everyKm, 100, 1_000_000);
  const everyMonths = blank(raw.everyMonths) ? null : inRange(raw.everyMonths, 1, 240);
  if ((!blank(raw.everyKm) && everyKm === null) || (!blank(raw.everyMonths) && everyMonths === null)) return null;
  if (everyKm === null && everyMonths === null) return null;
  const lastKm = blank(raw.lastKm) ? null : inRange(raw.lastKm, 0, 5_000_000);
  if (!blank(raw.lastKm) && lastKm === null) return null;
  const lastDate = raw.lastDate == null || raw.lastDate === '' ? null : isIsoDate(raw.lastDate) ? raw.lastDate : undefined;
  if (lastDate === undefined) return null;
  return {
    name,
    everyKm: everyKm === null ? null : Math.round(everyKm),
    everyMonths: everyMonths === null ? null : Math.round(everyMonths),
    lastKm: lastKm === null ? null : Math.round(lastKm),
    lastDate,
    note: str(raw.note, 80) ?? '',
  };
}

export function sanitizeDocItem(raw: unknown): Omit<DocItem, 'id'> | null {
  if (!isObj(raw)) return null;
  const name = str(raw.name, 40);
  if (!name || !isIsoDate(raw.expires)) return null;
  return { name, expires: raw.expires, note: str(raw.note, 80) ?? '' };
}

