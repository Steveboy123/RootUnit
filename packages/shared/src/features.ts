/**
 * v2 features that live beside the original vehicle/media/devices core: GPS, Pi health, trips, garage (fuel / service / documents),
 * weather, timers, scenes, quick actions, notes, lyrics, ambient lighting and the dashcam.
 *
 * Everything the UI shows continuously travels over the WebSocket as a named "service" (`ServiceMap`): the server sends the
 * whole map in the snapshot and then `{ t: 'svc', name, data }` whenever one changes. Larger or rarely-read documents (notes,
 * quick-action URLs, backups) are fetched over HTTP instead. All input validators live here so the server and the UI share one set of limits.
 */
import type { ThemeId } from './appearance';

const isObj = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);
const num = (v: unknown): number | null => (typeof v === 'number' && Number.isFinite(v) ? v : null);
const clampNum = (v: unknown, min: number, max: number): number | null => {
  const n = num(v);
  return n === null ? null : Math.min(max, Math.max(min, n));
};
const str = (v: unknown, max: number): string | null => (typeof v === 'string' ? v.trim().slice(0, max) : null);
/** The number if it is within [min, max], otherwise nothing: typed-in data that is out of range is refused, never quietly "corrected". */
const inRange = (v: unknown, min: number, max: number): number | null => {
  const n = num(v);
  return n !== null && n >= min && n <= max ? n : null;
};
const oneOf = <T extends string>(list: readonly T[], v: unknown): T | null => (typeof v === 'string' && (list as readonly string[]).includes(v) ? (v as T) : null);

/** `YYYY-MM-DD` that is a real calendar date. */
import type { FmState } from './fm';

export function isIsoDate(v: unknown): v is string {
  if (typeof v !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(v)) return false;
  const d = new Date(`${v}T00:00:00Z`);
  return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === v;
}

/** Ids generated by the server: short, URL-safe. Anything else is refused. */
export const ID_RE = /^[a-z0-9]{4,24}$/;

