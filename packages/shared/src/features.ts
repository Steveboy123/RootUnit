export interface ChecklistItem {
  id: string;
  text: string;
  done: boolean;
}

export interface Note {
  id: string;
  title: string;
  kind: 'note' | 'list';
  text: string;
  items: ChecklistItem[];
  pinned: boolean;
  updatedAt: number;
}

export const NOTE_LIMITS = { max: 80, title: 60, text: 4000, items: 100, item: 160 } as const;

export function sanitizeNote(raw: unknown): Omit<Note, 'id' | 'updatedAt'> | null {
  if (!isObj(raw)) return null;
  const kind = raw.kind === 'list' ? 'list' : 'note';
  const title = str(raw.title, NOTE_LIMITS.title) ?? '';
  const text = typeof raw.text === 'string' ? raw.text.slice(0, NOTE_LIMITS.text) : '';
  const items: ChecklistItem[] = [];
  if (Array.isArray(raw.items)) {
    for (const it of raw.items.slice(0, NOTE_LIMITS.items)) {
      if (!isObj(it)) continue;
      const t = str(it.text, NOTE_LIMITS.item);
      if (!t) continue;
      const id = typeof it.id === 'string' && ID_RE.test(it.id) ? it.id : '';
      items.push({ id, text: t, done: it.done === true });
    }
  }
  if (!title && !text && items.length === 0) return null;
  return { title: title || (kind === 'list' ? 'Checklist' : 'Note'), kind, text, items, pinned: raw.pinned === true };
}

