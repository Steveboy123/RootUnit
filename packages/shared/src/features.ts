export const SCENE_ICONS = ['moon', 'sun', 'road', 'coffee', 'party', 'parking', 'mountain', 'star'] as const;
export type SceneIcon = (typeof SCENE_ICONS)[number];
export const SCENE_TARGETS = ['home', 'drive', 'media', 'aa', 'apps'] as const;
export type SceneTarget = (typeof SCENE_TARGETS)[number];

/** Every field is optional: a scene only touches what it names. */
export interface SceneActions {
  theme?: ThemeId;
  /** Screen brightness, 5-100. */
  brightness?: number;
  /** System volume, 0-100. */
  volume?: number;
  lights?: { enabled: boolean; color?: string; brightness?: number };
  go?: SceneTarget;
  /** Start the standby clock. */
  standby?: boolean;
}

export interface Scene {
  id: string;
  name: string;
  icon: SceneIcon;
  actions: SceneActions;
}

export const SCENE_LIMITS = { max: 12 } as const;
const HEX = /^#[0-9a-fA-F]{6}$/;

export function sanitizeScene(raw: unknown, themeIds: readonly string[]): Omit<Scene, 'id'> | null {
  if (!isObj(raw)) return null;
  const name = str(raw.name, 24);
  if (!name) return null;
  const icon = oneOf(SCENE_ICONS, raw.icon) ?? 'star';
  const a = isObj(raw.actions) ? raw.actions : {};
  const actions: SceneActions = {};
  const theme = oneOf(themeIds as readonly ThemeId[], a.theme);
  if (theme) actions.theme = theme;
  const brightness = clampNum(a.brightness, 5, 100);
  if (brightness !== null) actions.brightness = Math.round(brightness);
  const volume = clampNum(a.volume, 0, 100);
  if (volume !== null) actions.volume = Math.round(volume);
  if (isObj(a.lights) && typeof a.lights.enabled === 'boolean') {
    const lights: NonNullable<SceneActions['lights']> = { enabled: a.lights.enabled };
    if (typeof a.lights.color === 'string' && HEX.test(a.lights.color)) lights.color = a.lights.color.toLowerCase();
    const lb = clampNum(a.lights.brightness, 1, 255);
    if (lb !== null) lights.brightness = Math.round(lb);
    actions.lights = lights;
  }
  const go = oneOf(SCENE_TARGETS, a.go);
  if (go) actions.go = go;
  if (a.standby === true) actions.standby = true;
  return { name, icon, actions };
}

// ---------------------------------------------------------------------------
// Quick actions (buttons that call a URL on the car's own network: garage door, Home Assistant, ...)
// ---------------------------------------------------------------------------

export const ACTION_ICONS = ['zap', 'door', 'home', 'lightbulb', 'lock', 'bell', 'fan', 'power'] as const;
export type ActionIcon = (typeof ACTION_ICONS)[number];

/** What every screen receives: never the address, which may carry a secret. */
export interface QuickActionPublic {
  id: string;
  name: string;
  icon: ActionIcon;
  confirm: boolean;
}

export interface QuickActionDef extends QuickActionPublic {
  method: 'GET' | 'POST';
  url: string;
  body: string;
}

export const ACTION_LIMITS = { max: 16 } as const;

export function sanitizeQuickAction(raw: unknown): Omit<QuickActionDef, 'id'> | null {
  if (!isObj(raw)) return null;
  const name = str(raw.name, 24);
  const url = str(raw.url, 400);
  if (!name || !url) return null;
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return null;
  }
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') return null;
  if (parsed.username || parsed.password) return null;
  const method = raw.method === 'POST' ? 'POST' : 'GET';
  const body = method === 'POST' ? (str(raw.body, 1000) ?? '') : '';
  return { name, icon: oneOf(ACTION_ICONS, raw.icon) ?? 'zap', confirm: raw.confirm === true, method, url: parsed.toString(), body };
}

