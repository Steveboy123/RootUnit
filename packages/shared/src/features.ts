export const TIMER_LIMITS = { maxItems: 12, minS: 5, maxS: 24 * 3600 } as const;

export function sanitizeTimerInput(raw: unknown): { label: string; kind: TimerKind; durationS: number } | null {
  if (!isObj(raw)) return null;
  const kind = oneOf(TIMER_KINDS, raw.kind) ?? 'timer';
  const durationS = inRange(raw.seconds, TIMER_LIMITS.minS, TIMER_LIMITS.maxS);
  if (durationS === null) return null;
  const fallback = kind === 'parking' ? 'Parking meter' : kind === 'sleep' ? 'Sleep timer' : 'Timer';
  return { kind, durationS: Math.round(durationS), label: str(raw.label, 30) || fallback };
}

