#!/usr/bin/env python3
"""Create safe Plymouth picture/text/script from the saved Boot Studio options.

Plymouth boots before Chromium: animation capabilities are more limited than
Boot Studio's live HTML preview. This renders the chosen artwork/colors/text
for early Linux boot, while the HTML screen carries the full animation onward.
"""
from __future__ import annotations
import json, math, sys
from pathlib import Path

try:
    from PIL import Image, ImageOps, ImageFilter, ImageDraw, ImageFont
except ImportError as e:
    sys.exit('Pillow is required for early boot sync: sudo apt install python3-pil')

project = Path(__file__).resolve().parents[2]
output = Path(sys.argv[1]) if len(sys.argv) > 1 else project / 'deploy/boot'
data_dir = Path(sys.argv[2]) if len(sys.argv) > 2 else project / 'data'
config_path = data_dir / 'boot-studio.json'
try:
    saved = json.loads(config_path.read_text())
    if not isinstance(saved, dict): saved = {}
except (OSError, ValueError):
    saved = {}
def pick(name,default):return saved.get(name,default)
PRESETS = {
    'neon':('#08040f','#ff2a93'),'glass':('#030b17','#74ddff'),
    'matrix':('#010b05','#44ff88'),'sunset':('#15070c','#ff9a46'),
    'minimal':('#08090c','#eeeeee'),
}
color,accent = PRESETS.get(pick('preset','neon'),(pick('bgColor','#08040f'),pick('accent','#ff2a93')))
def rgb(h,backup):
    if not isinstance(h,str) or len(h)!=7 or not h.startswith('#'):return backup
    try:return tuple(int(h[i:i+2],16) for i in (1,3,5))
    except ValueError:return backup
color = rgb(color,(8,4,15)); accent=rgb(accent,(255,42,147))

art_dir=project/'deploy/boot/art'
style=pick('image','armored')
if style not in ('original','transparent','armored','custom'):style='armored'
if style=='custom':
    art=next((art_dir/('mascot'+ext) for ext in ('.png','.jpg','.webp') if (art_dir/('mascot'+ext)).is_file()),art_dir/'armored.webp')
else:art=art_dir/(style+'.webp')
try:img=Image.open(art).convert('RGBA')
except (OSError,ValueError):img=Image.open(art_dir/'armored.webp').convert('RGBA')
if pick('mirror',False):img=ImageOps.mirror(img)
img.thumbnail((480,480),Image.Resampling.LANCZOS)
canvas=Image.new('RGBA',(490,490),(0,0,0,0)); x=(490-img.width)//2;y=(490-img.height)//2
canvas.alpha_composite(img,(x,y))
if not pick('showMascot',True):canvas.putalpha(0)
else:
    opacity=min(100,max(0,float(pick('opacity',100))))/100
    glow=min(100,max(0,float(pick('glow',48))))/100
    if glow>0:
        alpha=canvas.getchannel('A').filter(ImageFilter.GaussianBlur(15))
        alpha=alpha.point(lambda a:int(a*glow*.55))
        aura=Image.new('RGBA',canvas.size,accent+(0,));aura.putalpha(alpha)
        aura.alpha_composite(canvas);canvas=aura
    if opacity<1:canvas.putalpha(canvas.getchannel('A').point(lambda a:int(a*opacity)))

output.mkdir(parents=True,exist_ok=True)
canvas.save(output/'plymouth-mascot.png')
font_paths=['/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf','/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf']
font=next((p for p in font_paths if Path(p).exists()),None)
size=min(50,max(22,int(pick('titleSize',28)*1.35)))
try:face=ImageFont.truetype(font,size) if font else ImageFont.load_default()
except OSError:face=ImageFont.load_default()
title=str(pick('title','HEAD UNIT')).strip()[:38] or 'HEAD UNIT'
label=Image.new('RGBA',(900,170),(0,0,0,0)); draw=ImageDraw.Draw(label)
# Fit overly long custom headings to the width of the early splash.
while draw.textbbox((0,0),title,font=face,stroke_width=1)[2]>875 and size>15:
    size-=2;face=ImageFont.truetype(font,size) if font else ImageFont.load_default()
bbox=draw.textbbox((0,0),title,font=face,stroke_width=1)
w=bbox[2]-bbox[0]
draw.text((450-w/2,47),title,font=face,fill=accent+(255,),stroke_width=1,stroke_fill=(*color,255))
label.save(output/'plymouth-title.png')
red,green,blue=(v/255 for v in color)
posx=min(100,max(0,float(pick('positionX',50))))/100
posy=min(100,max(0,float(pick('positionY',44))))/100
motion=pick('motion','float')
# Safe Plymouth script primitives only; HTML animations take over afterwards.
phase='0.035' if motion not in ('none','hologram') else '0.0'
script=f'''# Generated by Head Unit Boot Studio (Plymouth Linux stage).
Window.SetBackgroundTopColor({red:.4f}, {green:.4f}, {blue:.4f});
Window.SetBackgroundBottomColor({red*.6:.4f}, {green*.6:.4f}, {blue*.6:.4f});
mascot.image = Image("plymouth-mascot.png");
mascot.sprite = Sprite(mascot.image);
mascot.sprite.SetZ(5);
caption.image = Image("plymouth-title.png");
caption.sprite = Sprite(caption.image);
caption.sprite.SetZ(6);
frame = 0;
fun refresh_callback () {{
 mascot.sprite.SetX(Window.GetWidth() * {posx:.3f} - mascot.image.GetWidth() / 2);
 mascot.sprite.SetY(Window.GetHeight() * {posy:.3f} - mascot.image.GetHeight() / 2 + Math.Sin(frame) * 4);
 caption.sprite.SetX((Window.GetWidth() - caption.image.GetWidth()) / 2);
 caption.sprite.SetY(Window.GetHeight() * 0.84 - caption.image.GetHeight() / 2);
 frame += {phase};
 mascot.sprite.SetOpacity(1.0);
}}
Plymouth.SetRefreshFunction(refresh_callback);
'''
(output/'headunit.script').write_text(script)
print('Rendered configured early boot assets in',output)
